import { writeFile } from 'node:fs/promises';
import { database } from '../tests/database.ts';

// The same migrations used by production and tests are the source of these types.
const db = await database();
try {
  const enums = (
    await db.query(
      `select t.oid::int,t.typname,array_agg(e.enumlabel order by e.enumsortorder) labels from pg_type t join pg_enum e on e.enumtypid=t.oid join pg_namespace n on n.oid=t.typnamespace where n.nspname='public' group by t.oid,t.typname`,
    )
  ).rows;
  const types = (await db.query(`select oid::int,typname,typelem::int from pg_type`)).rows;
  const typeMap = new Map(types.map((t) => [t.oid, t]));
  const convert = (oid) => {
    const info = typeMap.get(oid);
    const enumeration = enums.find((e) => e.oid === oid);
    if (enumeration) return enumeration.labels.map(JSON.stringify).join(' | ');
    if (info.typelem) return `(${convert(info.typelem)})[]`;
    if (['int2', 'int4', 'int8', 'numeric', 'float4', 'float8'].includes(info.typname))
      return 'number';
    if (info.typname === 'bool') return 'boolean';
    if (info.typname === 'void') return 'undefined';
    if (['json', 'jsonb', 'record'].includes(info.typname)) return 'Json';
    if (
      ['text', 'varchar', 'uuid', 'date', 'time', 'timestamp', 'timestamptz', 'name'].includes(
        info.typname,
      )
    )
      return 'string';
    return 'Json';
  };
  const relations = (
    await db.query(
      `select c.relname,c.relkind,a.attname,a.atttypid::int,a.attnotnull from pg_class c join pg_namespace n on n.oid=c.relnamespace join pg_attribute a on a.attrelid=c.oid where n.nspname='public' and c.relkind in('r','v') and a.attnum>0 and not a.attisdropped order by c.relname,a.attnum`,
    )
  ).rows;
  let output =
    '// Generated by npm run types:db. Do not edit manually.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: {\n';
  for (const [kind, label] of [
    ['r', 'Tables'],
    ['v', 'Views'],
  ]) {
    output += `${label}: {\n`;
    for (const name of [
      ...new Set(relations.filter((r) => r.relkind === kind).map((r) => r.relname)),
    ]) {
      output += `${name}: { Row: {\n`;
      const nullableViewColumns = {
        fault_history: ['maintained_by', 'maintained_at'],
        current_rules: ['approved_by'],
        latest_rules: ['approved_by'],
        debt_balances: ['debtor_id'],
        current_payments: [],
        scheduled_tasks: ['due_time', 'completed_by', 'completed_at'],
      };
      for (const column of relations.filter((r) => r.relname === name)) {
        const nullable =
          kind === 'v' && name in nullableViewColumns
            ? nullableViewColumns[name].includes(column.attname)
            : !column.attnotnull;
        output += `${column.attname}: ${convert(column.atttypid)}${nullable ? ' | null' : ''};\n`;
      }
      output += `}; ${kind === 'r' ? 'Insert: never; Update: never;' : ''} Relationships: [] };\n`;
    }
    output += '};\n';
  }
  output += 'Functions: {\n';
  const funcs = (
    await db.query(
      `select p.proname,p.pronargs,p.pronargdefaults,p.proargnames,p.proargtypes::oid[] args,p.prorettype::int,p.proretset,p.proallargtypes,p.proargmodes from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prorettype<>'trigger'::regtype order by proname`,
    )
  ).rows;
  for (const fn of funcs) {
    output += `${fn.proname}: { Args: ${fn.pronargs ? '{' : 'Record<string, never>'}`;
    for (let i = 0; i < fn.pronargs; i++)
      output += `${fn.proargnames[i]}${i >= fn.pronargs - fn.pronargdefaults ? '?' : ''}: ${convert(fn.args[i])} | null;`;
    if (fn.pronargs) output += '}';
    let result = convert(fn.prorettype);
    if (fn.proargmodes?.includes('t')) {
      result =
        '{' +
        fn.proargmodes
          .flatMap((mode, i) =>
            mode === 't' ? [`${fn.proargnames[i]}: ${convert(fn.proallargtypes[i])} | null;`] : [],
          )
          .join('') +
        '}';
    }
    output += `; Returns: ${result}${fn.proretset ? '[]' : ''} };\n`;
  }
  output += '}; Enums: {\n';
  for (const e of enums) output += `${e.typname}: ${convert(e.oid)};\n`;
  output += '}; CompositeTypes: Record<string, never>; } };\n';
  output +=
    'export type Relation = keyof Database["public"]["Tables"] | keyof Database["public"]["Views"];\nexport type Row<T extends Relation> = (Database["public"]["Tables"] & Database["public"]["Views"])[T]["Row"];\n';
  await writeFile('src/services/database.types.ts', output);
  console.log('Database types generated from migrations.');
} finally {
  await db.close();
}
